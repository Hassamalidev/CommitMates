import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

/**
 * Generates the self-hosted icon subset (CLAUDE.md §9.3): reads the Material Symbols
 * Rounded SVGs (Apache-2.0) for the icons the UI uses and writes their path data to
 * `packages/ui/src/icons/paths.generated.ts`. Run `pnpm icons:build` after editing the list.
 */

const repoRoot = path.resolve(import.meta.dirname, '..');
const uiRoot = path.join(repoRoot, 'packages/ui');
const output = path.join(uiRoot, 'src/icons/paths.generated.ts');

/** Material Symbols names in use. Keep sorted; add a name here before using it in a component. */
export const ICON_NAMES = [
  'arrow_forward',
  'bolt',
  'cancel',
  'check',
  'check_circle',
  'close',
  'computer',
  'content_copy',
  'dark_mode',
  'do_not_disturb_on',
  'error',
  'hourglass_top',
  'info',
  'keyboard_arrow_down',
  'light_mode',
  'lock',
  'menu',
  'open_in_new',
  'person',
  'progress_activity',
  'schedule',
  'search',
  'terminal',
  'unfold_more',
  'warning',
] as const;

const require = createRequire(path.join(uiRoot, 'package.json'));
const svgRoot = path.dirname(require.resolve('@material-symbols/svg-400/package.json'));

function readPath(name: string): string {
  const svg = readFileSync(path.join(svgRoot, 'rounded', `${name}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((match) => match[1]);
  if (paths.length === 0) throw new Error(`No path data in ${name}.svg`);
  return paths.join(' ');
}

const entries = ICON_NAMES.map((name) => `  ${name}: '${readPath(name)}',`);
const source = [
  '// Generated by scripts/build-icons.ts from Material Symbols Rounded (Apache-2.0). Do not edit.',
  '/** SVG path data on a `0 -960 960 960` view box. */',
  'export const ICON_PATHS = {',
  ...entries,
  '} as const;',
  '',
  'export type IconName = keyof typeof ICON_PATHS;',
  '',
].join('\n');

writeFileSync(output, source);
console.info(`Wrote ${ICON_NAMES.length} icons to ${path.relative(repoRoot, output)}`);
